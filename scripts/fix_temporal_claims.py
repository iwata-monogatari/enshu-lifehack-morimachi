def main() -> None:
    total = 0
    targets = [p for p in ROOT.rglob("*.html")
               if not ({".git", "_cache", "node_modules", "reports"} & set(p.relative_to(ROOT).parts))]
    targets += list((ROOT / "data").rglob("*.json"))

    for path in sorted(set(targets)):
        text = path.read_text(encoding="utf-8")
        new = text
        n = 0
        for before, after in REPLACEMENTS:
            if before in new:
                n += new.count(before)
                new = new.replace(before, after)
        if n:
            path.write_text(new, encoding="utf-8")
            print(f"  {path.relative_to(ROOT)}: {n} 箇所")
            total += n
    print(f"\n経過した予定表現を {total} 箇所修正しました")


if __name__ == "__main__":
    main()
